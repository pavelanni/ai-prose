#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.10,<3.13"
# dependencies = [
#   "kokoro>=0.9.4",
#   "numpy",
# ]
# ///
"""Narrate a post with Kokoro TTS, encode to MP3 and (optionally) upload to R2.

Usage:
    scripts/make_audio.py the-great-cicada --text-only   # just show what will be read
    scripts/make_audio.py the-great-cicada --no-upload   # synthesize to audio/<post>.mp3
    scripts/make_audio.py the-great-cicada               # synthesize + upload to R2

Requirements: uv, ffmpeg, espeak-ng (brew install espeak-ng on macOS),
and for uploading, `npx wrangler login` plus the R2 bucket name
(--bucket or the R2_BUCKET environment variable).
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
POSTS = REPO / "content" / "posts"
OUT_DIR = REPO / "audio"  # git-ignored build output
PUBLIC_BASE = "https://pub-d5cb528b6de54f13988ed3c57aee1756.r2.dev"
SAMPLE_RATE = 24000  # Kokoro's native rate
KOKORO_REPO = "hexgrad/Kokoro-82M"  # passed explicitly to avoid kokoro's "defaulting repo_id" warning

# Pauses (seconds) inserted around the text.
PARAGRAPH_PAUSE = 0.7
TITLE_PAUSE = 1.2


# --------------------------------------------------------------------------
# Markdown -> plain narration text
# --------------------------------------------------------------------------

def split_front_matter(md: str) -> tuple[dict[str, str], str]:
    """Return (simple key/value front matter, body). Handles '---' YAML blocks."""
    meta: dict[str, str] = {}
    m = re.match(r"\A---\n(.*?)\n---\n", md, re.DOTALL)
    if not m:
        return meta, md
    for line in m.group(1).splitlines():
        km = re.match(r"^(\w+):\s*'?(.*?)'?\s*$", line)
        if km:
            meta[km.group(1)] = km.group(2)
    return meta, md[m.end():]


def clean_paragraph(p: str) -> str:
    p = re.sub(r"!\[[^\]]*\]\([^)]*\)", "", p)           # images
    p = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", p)        # links -> link text
    p = re.sub(r"(\*\*|__)(.+?)\1", r"\2", p)             # bold
    p = re.sub(r"(?<!\w)([*_])(.+?)\1(?!\w)", r"\2", p)   # italics
    p = re.sub(r"^#+\s*", "", p)                          # heading marks
    p = re.sub(r"`([^`]*)`", r"\1", p)                    # inline code
    p = p.replace("—", ", ").replace("–", ", ")           # dashes read better as pauses
    p = re.sub(r"\s*\n\s*", " ", p)                       # join hard-wrapped lines
    p = re.sub(r"\s+", " ", p).strip()
    return p


def extract_paragraphs(md: str, include_title: bool = True) -> list[str]:
    meta, body = split_front_matter(md)

    # Drop shortcodes ({{< ... >}} and {{% ... %}}).
    body = re.sub(r"\{\{[<%].*?[>%]\}\}", "", body, flags=re.DOTALL)

    paragraphs: list[str] = []
    for block in re.split(r"\n\s*\n", body):
        block = block.strip()
        if not block:
            continue
        # Blockquotes hold the author's original prompt, not the story.
        if all(line.lstrip().startswith(">") for line in block.splitlines()):
            continue
        # Credit lines such as "_The cover image was generated by DALL-E..._".
        if re.fullmatch(r"[_*].*cover image.*[_*]", block, re.IGNORECASE | re.DOTALL):
            continue
        # Horizontal rules / stray punctuation-only blocks.
        if re.fullmatch(r"[-*_\s]+", block):
            continue
        text = clean_paragraph(block)
        if text:
            paragraphs.append(text)

    if include_title and meta.get("title"):
        paragraphs.insert(0, meta["title"] + ".")
    return paragraphs


# --------------------------------------------------------------------------
# Synthesis
# --------------------------------------------------------------------------

def synthesize(paragraphs: list[str], voice: str, speed: float, lang: str, has_title: bool):
    """Yield float32 numpy arrays (24 kHz mono) for the whole narration."""
    import warnings

    # Kokoro's dependencies (torch) emit deprecation noise that we can't fix here.
    warnings.filterwarnings("ignore", category=UserWarning, module=r"torch\.nn\.modules\.rnn")
    warnings.filterwarnings("ignore", category=FutureWarning, module=r"torch\.")

    import numpy as np
    from kokoro import KPipeline

    pipeline = KPipeline(lang_code=lang, repo_id=KOKORO_REPO)
    total = len(paragraphs)
    for i, para in enumerate(paragraphs, 1):
        print(f"  [{i}/{total}] {para[:60]}{'...' if len(para) > 60 else ''}", file=sys.stderr)
        for _, _, audio in pipeline(para, voice=voice, speed=speed):
            yield np.asarray(audio, dtype=np.float32)
        pause = TITLE_PAUSE if (has_title and i == 1) else PARAGRAPH_PAUSE
        yield np.zeros(int(SAMPLE_RATE * pause), dtype=np.float32)


def encode_mp3(chunks, out_path: Path, bitrate: str) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        "ffmpeg", "-y", "-loglevel", "error",
        "-f", "f32le", "-ar", str(SAMPLE_RATE), "-ac", "1", "-i", "-",
        # Duplicate the mono signal into both channels so it plays in both ears.
        "-af", "pan=stereo|c0=c0|c1=c0",
        "-codec:a", "libmp3lame", "-b:a", bitrate,
        str(out_path),
    ]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE)
    assert proc.stdin is not None
    try:
        for chunk in chunks:
            proc.stdin.write(chunk.tobytes())
    finally:
        proc.stdin.close()
    if proc.wait() != 0:
        sys.exit("ffmpeg failed")


# --------------------------------------------------------------------------
# Upload
# --------------------------------------------------------------------------

def upload(mp3: Path, bucket: str, key: str) -> None:
    cmd = [
        "npx", "wrangler", "r2", "object", "put", f"{bucket}/{key}",
        "--file", str(mp3), "--content-type", "audio/mpeg", "--remote",
    ]
    print("  $ " + " ".join(cmd), file=sys.stderr)
    subprocess.run(cmd, check=True)


# --------------------------------------------------------------------------

def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("post", help="post directory name under content/posts/")
    ap.add_argument("--text-only", action="store_true", help="print the cleaned narration text and exit")
    ap.add_argument("--no-upload", action="store_true", help="synthesize but do not upload")
    ap.add_argument("--no-title", action="store_true", help="do not read the title first")
    ap.add_argument("--voice", default="af_heart", help="Kokoro voice (default: af_heart)")
    ap.add_argument("--lang", default="a", help="Kokoro lang code: a=US English, b=UK English (default: a)")
    ap.add_argument("--speed", type=float, default=1.0)
    ap.add_argument("--bitrate", default="96k")
    ap.add_argument("--bucket", default=os.environ.get("R2_BUCKET"), help="R2 bucket name (or $R2_BUCKET)")
    args = ap.parse_args()

    post_file = POSTS / args.post / "index.md"
    if not post_file.exists():
        sys.exit(f"No such post: {post_file}")

    paragraphs = extract_paragraphs(post_file.read_text(encoding="utf-8"), include_title=not args.no_title)

    if args.text_only:
        print("\n\n".join(paragraphs))
        words = sum(len(p.split()) for p in paragraphs)
        print(f"\n[{len(paragraphs)} paragraphs, {words} words, ~{words / 150:.1f} min]", file=sys.stderr)
        return

    if not args.no_upload and not args.bucket:
        sys.exit("Set --bucket or $R2_BUCKET (or pass --no-upload).")

    mp3 = OUT_DIR / f"{args.post}.mp3"
    print(f"Synthesizing {args.post} with voice {args.voice}...", file=sys.stderr)
    chunks = synthesize(paragraphs, args.voice, args.speed, args.lang, has_title=not args.no_title)
    encode_mp3(chunks, mp3, args.bitrate)
    print(f"Wrote {mp3} ({mp3.stat().st_size / 1e6:.1f} MB)", file=sys.stderr)

    if args.no_upload:
        print("Skipped upload. Listen first, then re-run without --no-upload.", file=sys.stderr)
    else:
        upload(mp3, args.bucket, mp3.name)

    print("\nAdd this line to the post:\n")
    print(f'{{{{< audio-player url="{PUBLIC_BASE}/{mp3.name}" >}}}}')


if __name__ == "__main__":
    main()
